/**
 * Bundles the Linux Terminal Voice Companion into ONE dependency-free Node script:
 *   widget/release/linguacode-voice.mjs  (+ SHA256SUMS, checked by scripts/install-widget.sh)
 * The release file is committed so the curl | bash installer can fetch it straight from the repo.
 */
import { build } from 'vite';
import { createHash } from 'node:crypto';
import { chmod, readFile, writeFile } from 'node:fs/promises';

const outDir = 'widget/release';
const file = 'linguacode-voice.mjs';

await build({
  configFile: false,
  publicDir: false,
  logLevel: 'warn',
  ssr: { noExternal: true, target: 'node' },
  build: {
    ssr: 'widget/src/cli.ts',
    outDir,
    emptyOutDir: true,
    minify: false,
    target: 'node18',
    rollupOptions: {
      output: {
        format: 'es',
        entryFileNames: file,
        banner: '#!/usr/bin/env node\n// Generated by scripts/build-widget.mjs from widget/src/cli.ts — do not edit.',
      },
    },
  },
});

const bundle = await readFile(`${outDir}/${file}`);
await chmod(`${outDir}/${file}`, 0o755);
const sum = createHash('sha256').update(bundle).digest('hex');
await writeFile(`${outDir}/SHA256SUMS`, `${sum}  ${file}\n`);
console.log(`Widget built → ${outDir}/${file} (${(bundle.length / 1024).toFixed(1)} KB, sha256 ${sum.slice(0, 12)}…)`);
